/**
 * @file logger.hpp
 * @brief Заголовочный файл библиотеки логирования
 * 
 * Библиотека с потокобезопасным singleton-логгером для записи
 * сообщений в файл с временными метками, уровнями важности и текстом сообщения.
 */

#ifndef LOGGER_HPP
#define LOGGER_HPP

#include <string>
#include <fstream>
#include <mutex>
#include <atomic>

/**
 * @namespace logger
 * @brief Пространство имён библиотеки логирования
 *
 * Содержит все классы, перечисления и функции, необходимые
 * для работы системы журналирования сообщений.
 */
namespace logger {
    /**
     * @enum Level
     * @brief Уровни важности сообщений журнала
     * 
     * Определяет три уровня важности, где STATE1 — наивысший,
     * STATE3 — низший. При фильтрации сообщения с уровнем ниже
     * установленного порога игнорируются.
     */
    // TODO Придумать название получше.
    enum class Level {
        STATE1,
        STATE2,
        STATE3
    };

    /**
     * @class Logger
     * @brief Потокобезопасный singleton-логгер
     *
     * Реализует паттерн "Одиночка" (Singleton) с использованием
     * идиомы Мейерса. Обеспечивает потокобезопасную запись
     * сообщений в текстовый файл с автоматическими временными метками. Круто.
     *
     * @note Перед использованием необходимо вызвать метод init().
     *       Класс некопируемый и неперемещаемый.
     *
     * Пример:
     * @code
     * // init
     * Logger::instance().init("app.log", Level::INFO);
     *
     * // Запись сообщений
     * Logger::instance().log(Level::ERROR, "Сервер недоступен и тд..."); // с указ-ым уровнем
     * Logger::instance().log("Обычное сообщение"); // с уровнем по умолчанию
     * @endcode
     */
    class Logger {
        public:
            /**
             * @brief Получить экземпляр singleton-логгера
             * 
             * Гарантирует потокобезопасное создание единственного
             * экземпляра класса при первом вызове (C++11 и выше).
             * 
             * @return Logger& Ссылка на единственный экземпляр логгера
             */
            static Logger& instance();

            /**
             * @brief Инициализировать логгер
             *
             * Открывает файл журнала и устанавливает уровень важности
             * по умолчанию. *При необходимости создаёт все родительские
             * директории для файла журнала.
             *
             * @param filename Путь к файлу журнала. Если файл существует,
             *  новые записи добавляются в конец.
             * @param default_level Уровень важности по умолчанию для
             *  сообщений без явно указанного уровня.
             *  По умолчанию — Level::STATE3.
             *
             * @return true Инициализация прошла успешно
             * @return false Ошибка инициализации
             *
             * @note Повторный вызов init() после успешной инициализации
             *       вернёт false.
             */
            bool init(const std::string& filename, Level default_level = Level::STATE3);
            
            /**
             * @brief Изменить уровень важности по умолчанию
             *
             * Меняет порог фильтрации сообщений. Сообщения с уровнем
             * ниже установленного не будут записываться в журнал.
             * Само изменение логируется с уровнем STATE3.
             *
             * @param level Новый уровень важности по умолчанию
             *
             * @note Потокобезопасен. Если логгер не инициализирован,
             *  вызов игнорируется.
             */
            void setDefaultLevel(Level level) noexcept;
            
            /**
             * @brief Получить текущий уровень важности по умолчанию
             * 
             * @return Level Текущий уровень фильтрации сообщений
             * 
             * @note Потокобезопасен. Если логгер не инициализирован
             *  то возвращает значение по умолчанию (Level::INFO).
             */
            Level getDefaultLevel() const noexcept;
            
            /**
             * @brief Записать сообщение в журнал
             * 
             * Потокобезопасно записывает сообщение с указанным уровнем
             * важности в файл журнала. Сообщение игнорируется если
             * его уровень ниже установленного порога фильтрации.
             * 
             * @param level Уровень важности сообщения
             * @param message Текст сообщения (без символов новой строки!!!)
             * 
             * @return true Сообщение успешно записано или отфильтровано
             * @return false Ошибка записи - файл недоступен или логгер
             *  не инициализирован
             * 
             * @note Добавляет временную метку и уровень важности
             *  автоматически. Символ новой строки добавляется
             *  в конец записи.
             */
            bool log(Level level, const std::string& message);
            
            /**
             * @brief Записать сообщение с уровнем по умолчанию
             * 
             * Перегруженный метод использующий текущий уровень
             * важности по умолчанию.
             * 
             * @param message Текст сообщения
             * 
             * @return true Сообщение успешно записано или отфильтровано
             * @return false Ошибка записи или логгер не инициализирован
             * 
             * @see log(Level, const std::string&)
             */
            bool log(const std::string& message);

        private:
            /**
             * @brief Конструктор по умолчанию (приватный)
             *
             * Запрещает прямое создание экземпляров класса.
             */
            Logger() = default;
            /**
             * @brief Деструктор
             * 
             * Автоматически закрывает файл журнала при уничтожении
             * единственного экземпляра логгера.
             */
            ~Logger();
            // Запрет копирования и присваивания
            Logger(const Logger&) = delete;
            Logger& operator=(const Logger&) = delete;

            /**
             * @brief Сформировать временную метку
             *
             * @return std::string Строка в формате "YYYY-MM-DD HH:MM:SS.mmm"
             *
             * @note Использует системное время.
             */
            static std::string timestamp();
            /**
             * @brief Проверить нужно ли записывать сообщение
             * 
             * Сообщение записывается если его уровень важности
             * не ниже (меньше или равен) установленного порога.
             * STATE1 (0) — всегда записывается.
             * 
             * @param level Проверяемый уровень важности
             * 
             * @return true Сообщение должно быть записано
             * @return false Сообщение должно быть отфильтровано
             * 
             * @note Уровни сравниваются по их целочисленным значениям
             *  (STATE1=0 ... INFO=2). Меньшее значение
             *  означает более высокую важность.
             */
            bool shouldLog(Level level) const noexcept;

            /**
             * @brief Преобразовать уровень в строку
             *
             * @param level Уровень важности
             *
             * @return std::string Строковое представление уровня
             *  ("STATE1", "STATE2", "STATE3" или "UNKNOWN")
             */
            static std::string levelToString(Level level);

            std::atomic<bool> initialized_{false}; ///< Флаг инициализации
            std::atomic<Level> defaultLevel_{Level::STATE3}; ///< Уровень по умолчанию
            std::string filename_; ///< Путь к файлу журнала
            std::ofstream file_; ///< Поток файла журнала
            std::mutex writeMutex_; ///< Мьютекс для синхронизации записи
    };

} // namespace logger
#endif // LOGGER_HPP
